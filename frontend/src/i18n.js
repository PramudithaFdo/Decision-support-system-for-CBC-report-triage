const initialLanguage = localStorage.getItem(STORAGE_KEY) === 'si' ? 'si' : 'en';
export const language = ref(initialLanguage);

export function setLanguage(nextLanguage) {
  language.value = nextLanguage === 'si' ? 'si' : 'en';
  localStorage.setItem(STORAGE_KEY, language.value);
}

export function useI18n() {
  const t = (key) => messages[language.value][key] || messages.en[key] || key;
  const category = (value) => {
    const map = {
      Routine: 'routine',
      'Abnormal non-critical': 'abnormalNonCritical',
      'Critical / urgent': 'criticalUrgent',
      'Uncertain / manual review': 'uncertainManualReview',
      Pending: 'pending',
    };
    return t(map[value] || value);
  };
  const source = (value, label) => {
    const map = {
      neerogya_healthcare_polonnaruwa: 'neerogyaClinicalData',
      real_deidentified: 'realDeidentifiedData',
      pending_ethics_review: 'pendingEthicsReview',
      research_deidentified: 'researchDeidentifiedData',
      manual_entry: 'researchDatasetImport',
    };
    return t(map[value] || label || value || 'researchDatasetImport');
  };

  return {
    language,
    setLanguage,
    t,
    category,
    source,
    isSinhala: computed(() => language.value === 'si'),
  };
}
